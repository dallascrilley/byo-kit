#!/usr/bin/env node
// Flattens src/ into one self-contained ES module: dist/byo-kit.js.
// Standard library only. Output is deterministic, so CI can check it with --check.
//
// Rules for source files (the script fails loudly if they are broken):
//   - imports are one-line named imports: import { a, b } from './x.js';
//   - exports are `export function|class|const|let` or `export { a } from './x.js'`
//   - top-level names are unique across all modules
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = resolve(ROOT, 'src/index.js');
const OUT = resolve(ROOT, 'dist/byo-kit.js');

const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm;
const REEXPORT_RE = /^export\s*\{([^}]*)\}\s*from\s*'([^']+)';?[ \t]*$/gm;
const DECL_RE = /^(?:export\s+)?(?:async\s+)?(?:function\s*\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;
const EXPORT_DECL_RE = /^export\s+(?:async\s+)?(?:function\s*\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

const names = (list) => list.split(',').map((s) => s.trim()).filter(Boolean);
const fail = (msg) => {
  process.stderr.write('bundle: ' + msg + '\n');
  process.exit(1);
};

const modules = new Map(); // path -> { src, imports, reexports, exports }
const order = [];

function visit(path) {
  if (modules.has(path)) return;
  if (!existsSync(path)) fail('missing module ' + relative(ROOT, path));
  const src = readFileSync(path, 'utf8');
  const imports = [...src.matchAll(IMPORT_RE)].map((m) => ({ names: names(m[1]), from: resolve(dirname(path), m[2]) }));
  const reexports = [...src.matchAll(REEXPORT_RE)].map((m) => ({ names: names(m[1]), from: resolve(dirname(path), m[2]) }));
  const exports = new Set([...src.matchAll(EXPORT_DECL_RE)].map((m) => m[1]));
  modules.set(path, { src, imports, reexports, exports });
  for (const dep of [...imports, ...reexports]) visit(dep.from);
  order.push(path);
}
visit(ENTRY);

// Every imported name must be exported by its source module.
for (const [path, mod] of modules) {
  for (const dep of [...mod.imports, ...mod.reexports]) {
    const target = modules.get(dep.from);
    for (const n of dep.names) {
      if (!target.exports.has(n)) fail(relative(ROOT, path) + ' imports "' + n + '" which ' + relative(ROOT, dep.from) + ' does not export');
    }
  }
}

const seen = new Map();
const parts = [];
for (const path of order) {
  const mod = modules.get(path);
  for (const m of mod.src.matchAll(DECL_RE)) {
    if (seen.has(m[1])) fail('duplicate top-level name "' + m[1] + '" in ' + relative(ROOT, path) + ' and ' + seen.get(m[1]));
    seen.set(m[1], relative(ROOT, path));
  }
  const body = mod.src
    .replace(IMPORT_RE, '')
    .replace(REEXPORT_RE, '')
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  if (/^\s*(import|export)\s/m.test(body)) fail('unsupported import or export syntax in ' + relative(ROOT, path));
  if (body) parts.push('// ---- ' + relative(ROOT, path) + '\n' + body);
}

const entry = modules.get(ENTRY);
const exported = entry.reexports.flatMap((r) => r.names);
const pkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
const header =
  '// byo-kit ' + pkg.version + ' (MIT). Generated by scripts/bundle.mjs from src/. Do not edit.\n' +
  '// Bring your own data and bring your own key, for static demos. No dependencies.\n';
const output = header + '\n' + parts.join('\n\n') + '\n\nexport {\n  ' + exported.join(',\n  ') + ',\n};\n';

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== output) fail('dist/byo-kit.js is out of date. Run: node scripts/bundle.mjs');
  process.stdout.write('bundle: dist/byo-kit.js is up to date\n');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, output);
  process.stdout.write('bundle: wrote dist/byo-kit.js (' + Buffer.byteLength(output) + ' bytes, ' + exported.length + ' exports)\n');
}
